  /* ---------- 10. 题目回顾 ---------- */
  function buildReview() {
    var list = document.getElementById('review-list');
    list.innerHTML = '';
    QUESTIONS.forEach(function (item, qi) {
      var chosen = answers[qi];
      var block = document.createElement('div');
      block.style.cssText = 'background:rgba(27,29,51,0.45);border:1px solid var(--rule);border-radius:12px;padding:1rem 1.1rem;margin-bottom:0.8rem;';
      var head = '<div style="font-family:var(--font-code);color:var(--accent2);font-size:0.82rem;margin-bottom:0.5rem;">第 ' + (qi + 1) + ' 题 · ' + item.theme + '</div>';
      var q = '<div style="font-family:var(--font-serif);font-weight:700;margin-bottom:0.7rem;">' + item.q + '</div>';
      var optsHtml = '';
      item.opts.forEach(function (opt, oi) {
        var isChosen = (opt.f === chosen);
        var fn = FUNCTIONS[opt.f];
        var style = 'display:flex;justify-content:space-between;gap:0.8rem;padding:0.5rem 0.7rem;border-radius:8px;margin-bottom:0.35rem;font-size:0.9rem;';
        if (isChosen) {
          style += 'background:rgba(167,139,250,0.16);border:1px solid var(--accent);color:var(--ink);';
        } else {
          style += 'color:var(--muted);border:1px solid transparent;';
        }
        optsHtml += '<div style="' + style + '"><span>' + String.fromCharCode(65 + oi) + '. ' + opt.t + '</span>' +
          '<span style="font-family:var(--font-code);color:' + (isChosen ? 'var(--accent2)' : 'var(--muted)') + ';white-space:nowrap;">' + fn.code + ' ' + fn.name + '</span></div>';
      });
      var motiveHtml = '';
      var motiveFunc = motiveAnswers[qi];
      if (motiveFunc) {
        var chosenOpt = null;
        item.opts.forEach(function (opt) { if (opt.f === chosen) chosenOpt = opt; });
        if (chosenOpt) {
          var mIdx = -1;
          chosenOpt.motives.forEach(function (m, i) { if (m.func === motiveFunc) mIdx = i; });
          if (mIdx >= 0) {
            var mText = chosenOpt.motives[mIdx].text;
            var mFn = FUNCTIONS[motiveFunc];
            motiveHtml =
              '<div style="margin-top:0.85rem;padding-top:0.75rem;border-top:1px solid var(--rule);">' +
              '<div style="color:var(--muted);font-size:0.88rem;"><span style="color:var(--accent2);font-family:var(--font-code);">动机选择：</span>' + mText + '</div>' +
              '<div style="color:var(--muted);font-size:0.82rem;margin-top:0.3rem;">该动机对应倾向：' + mFn.code + ' ' + mFn.name + '</div>' +
              '</div>';
          }
        }
      }
      block.innerHTML = head + q + '<div>' + optsHtml + '</div>' + motiveHtml;
      list.appendChild(block);
    });
  }

