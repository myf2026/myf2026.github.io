  /* ---------- 6. 渲染题目 ---------- */
  function renderQuestion() {
    var item = QUESTIONS[current];
    elQNum.textContent = current + 1;
    elQTheme.textContent = item.theme;
    elProgress.style.width = ((current * 2 + 1) / (TOTAL * 2) * 100) + '%';
    elQuestion.textContent = item.q;

    elOptions.innerHTML = '';
    item.opts.forEach(function (opt, idx) {
      var btn = document.createElement('button');
      btn.className = 'option';
      btn.type = 'button';
      btn.setAttribute('data-func', opt.f);
      if (answers[current] === opt.f) btn.classList.add('selected');
      btn.innerHTML =
        '<span class="marker">' + String.fromCharCode(65 + idx) + '</span>' +
        '<span class="text">' + opt.t + '</span>';
      btn.addEventListener('click', function () { selectOption(opt.f, btn); });
      elOptions.appendChild(btn);
    });

    elPrev.style.visibility = current === 0 ? 'hidden' : 'visible';
    elNext.textContent = '继续：选择动机';
  }

  function selectOption(func, btn) {
    answers[current] = func;
    var all = elOptions.querySelectorAll('.option');
    all.forEach(function (o) { o.classList.remove('selected'); });
    btn.classList.add('selected');
  }

  function renderMotiveQuestion() {
    var item = QUESTIONS[current];
    var selectedFunc = answers[current];
    var selectedOpt = null;
    item.opts.forEach(function (opt) {
      if (opt.f === selectedFunc) selectedOpt = opt;
    });
    if (!selectedOpt) return;

    elQNum.textContent = current + 1;
    elQTheme.textContent = '动机追问';
    elProgress.style.width = ((current * 2 + 2) / (TOTAL * 2) * 100) + '%';
    elQuestion.textContent = '你刚才选择了："' + selectedOpt.t + '"。更接近你内心原因的是？';
    elOptions.innerHTML = '';

    selectedOpt.motives.forEach(function (m, idx) {
      var btn = document.createElement('button');
      btn.className = 'option';
      btn.type = 'button';
      btn.setAttribute('data-func', m.func);
      if (motiveAnswers[current] === m.func) btn.classList.add('selected');
      btn.innerHTML =
        '<span class="marker">' + String.fromCharCode(65 + idx) + '</span>' +
        '<span class="text">' + m.text + '</span>';
      btn.addEventListener('click', function () { selectMotive(m.func, btn); });
      elOptions.appendChild(btn);
    });

    elPrev.style.visibility = 'visible';
    elNext.textContent = current === TOTAL - 1 ? '查看结果' : '下一题';
  }

  function selectMotive(func, btn) {
    motiveAnswers[current] = func;
    var all = elOptions.querySelectorAll('.option');
    all.forEach(function (o) { o.classList.remove('selected'); });
    btn.classList.add('selected');
  }

  /* ---------- 7. 导航 ---------- */
  function goNext() {
    if (phase === 'main' && !answers[current]) {
      var orig = elNext.textContent;
      elNext.textContent = '请先选择一项';
      elNext.style.opacity = '0.6';
      setTimeout(function () { elNext.textContent = orig; elNext.style.opacity = '1'; }, 1100);
      return;
    }
    if (phase === 'main') {
      phase = 'motive';
      renderMotiveQuestion();
      return;
    }
    if (!motiveAnswers[current]) {
      var old = elNext.textContent;
      elNext.textContent = '请选择一个动机';
      elNext.style.opacity = '0.6';
      setTimeout(function () { elNext.textContent = old; elNext.style.opacity = '1'; }, 1200);
      return;
    }
    if (current < TOTAL - 1) {
      current++;
      phase = 'main';
      renderQuestion();
    } else {
      computeAndShowResult();
    }
  }
  function goPrev() {
    if (phase === 'motive') {
      phase = 'main';
      renderQuestion();
      return;
    }
    if (current > 0) {
      current--;
      phase = 'motive';
      renderMotiveQuestion();
    }
  }

  /* ---------- 8. 计分与类型推导（荣格功能—态度规则） ---------- */
  function computeScores() {
    var scores = {};
    FUNC_ORDER.forEach(function (f) { scores[f] = 0; });
    motiveAnswers.forEach(function (func) {
      if (func) scores[func]++;
    });
    return scores;
  }

  // 辅助：功能的类别(P/J)与态度(E/I)
  function catOf(f) { return FUNCTIONS[f].cat; }
  function attOf(f) { return FUNCTIONS[f].att; }
  function letterOf(f) { return f.charAt(0); }      // S/N/T/F

  function deriveType(scores) {
    // 主导 = 全局最高分功能（并列时：先比较所在类别总分，再按固定序）
    var ranked = FUNC_ORDER.slice().sort(function (a, b) {
      if (scores[b] !== scores[a]) return scores[b] - scores[a];
      // 同分时：类别总分高者优先
      var catA = sumCat(scores, catOf(a));
      var catB = sumCat(scores, catOf(b));
      if (catB !== catA) return catB - catA;
      return FUNC_ORDER.indexOf(a) - FUNC_ORDER.indexOf(b);
    });
    var dom = ranked[0];

    // 辅助 = 与主导"态度相反、类别相反"的两个候选中得分较高者
    var domCat = catOf(dom), domAtt = attOf(dom);
    var auxCandidates = FUNC_ORDER.filter(function (f) {
      return catOf(f) !== domCat && attOf(f) !== domAtt;
    });
    auxCandidates.sort(function (a, b) {
      if (scores[b] !== scores[a]) return scores[b] - scores[a];
      return FUNC_ORDER.indexOf(a) - FUNC_ORDER.indexOf(b);
    });
    var aux = auxCandidates[0];

    // 推导四字母
    var perceivingFunc = (catOf(dom) === 'P') ? dom : aux;
    var judgingFunc = (catOf(dom) === 'J') ? dom : aux;
    var EI = attOf(dom);
    var SN = (letterOf(perceivingFunc) === 'S') ? 'S' : 'N';
    var TF = (letterOf(judgingFunc) === 'T') ? 'T' : 'F';
    var JP;
    if (EI === 'E') {
      JP = (catOf(dom) === 'J') ? 'J' : 'P';        // 外倾者由主导定 J/P
    } else {
      JP = (catOf(dom) === 'P') ? 'J' : 'P';        // 内倾者：主导为感知→J，主导为判断→P
    }
    var type = EI + SN + TF + JP;
    var tertiary = OPPOSITE_POLE[aux];
    var inferior = OPPOSITE_POLE[dom];
    var sun = [dom, aux, tertiary, inferior];
    var shadow = sun.map(function (f) { return OPPOSITE_ATTITUDE[f]; });
    return {
      dom: dom,
      aux: aux,
      tertiary: tertiary,
      inferior: inferior,
      sun: sun,
      shadow: shadow,
      type: type,
      perceivingFunc: perceivingFunc,
      judgingFunc: judgingFunc
    };
  }
  function sumCat(scores, cat) {
    return FUNC_ORDER.filter(function (f) { return catOf(f) === cat; })
      .reduce(function (s, f) { return s + scores[f]; }, 0);
  }

  function guideBlock(title, text) {
    return '<div style="margin-top:0.55rem;padding:0.62rem 0.75rem;border:1px solid var(--rule);border-radius:10px;background:rgba(14,15,30,0.26);">' +
      '<div style="font-family:var(--font-code);font-size:0.72rem;letter-spacing:0.12em;color:var(--accent2);margin-bottom:0.25rem;">' + title + '</div>' +
      '<div style="color:var(--muted);font-size:0.88rem;line-height:1.65;">' + text + '</div>' +
      '</div>';
  }

  /* ---------- 9. 渲染结果 ---------- */
